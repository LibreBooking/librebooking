    /**
     * Swedish standard: ISO 8601 dates (YYYY-MM-DD) and 24-hour clock.
     * Only the full day name ('l') is translated by format_date, so avoid
     * 'D', 'M' and 'F' which would render in English.
     *
     * @return array
     */
    protected function _LoadDates()
    {
        $dates = parent::_LoadDates();

        $dates['general_date'] = 'Y-m-d';
        $dates['general_datetime'] = 'Y-m-d H:i';
        $dates['short_datetime'] = 'Y-m-d H:i';
        $dates['schedule_daily'] = 'l Y-m-d';
        $dates['reservation_email'] = 'l Y-m-d \k\l\. H:i';
        $dates['res_popup'] = 'Y-m-d H:i';
        $dates['res_popup_time'] = 'H:i';
        $dates['short_reservation_date'] = 'Y-m-d H:i';
        $dates['dashboard'] = 'l Y-m-d H:i';
        $dates['period_time'] = 'H:i';
        $dates['mobile_reservation_date'] = 'j/n H:i';
        $dates['general_date_js'] = 'yy-mm-dd';
        $dates['general_time_js'] = 'HH:mm';
        $dates['momentjs_datetime'] = 'YYYY-MM-DD HH:mm';
        $dates['calendar_time'] = 'H:i';
        $dates['calendar_dates'] = 'j/n';
        $dates['embedded_date'] = 'j/n';
        $dates['embedded_time'] = 'H:i';
        $dates['embedded_datetime'] = 'j/n H:i';
        $dates['report_date'] = '%d/%m';

        $this->Dates = $dates;
        return $this->Dates;
    }

